"""Learning-pathway-generated nodes are view-only *by design*, not flagged as
non-standard "view-only (not matching 'var = pnl.Type(' pattern)" vars (#822).

The Montague, Dayan & Sejnowski (1996) TD-learning reference model pulls its
objective and target mechanisms out of ``add_td_learning_pathway(...)
.learning_components`` by subscript:

    prediction_error_mechanism = learning_related_components[pnl.OBJECTIVE_MECHANISM]
    target_mechanism           = learning_related_components[pnl.TARGET_MECHANISM]

Those aren't authored via ``var = pnl.Type(...)``, so the introspector used to
lump them into ``readOnlyVars`` and surface a warning that read like the model's
code was malformed. They're now classified as ``generatedVars`` (calm notice).
"""

from pathlib import Path

from app.services.sandbox_worker import task_introspect

REFERENCE_MODEL = (
    Path(__file__).parent.parent / "reference_models" / "MontagueDayanSejnowski96.py"
)


def _diagnostics():
    result = task_introspect({"file_path": str(REFERENCE_MODEL)})
    assert "error" not in result, result.get("error")
    return result["diagnostics"]


def test_learning_generated_nodes_classified_as_generated():
    d = _diagnostics()
    generated = set(d["generatedVars"])
    assert {"prediction_error_mechanism", "target_mechanism"} <= generated, generated
    # And not double-counted as non-standard view-only vars.
    assert "prediction_error_mechanism" not in d["readOnlyVars"]
    assert "target_mechanism" not in d["readOnlyVars"]


def test_no_not_matching_warning_when_only_generated_nodes_are_view_only():
    d = _diagnostics()
    assert not any("not matching" in w for w in d["warnings"]), d["warnings"]
    assert any(
        "generated by a learning pathway" in n for n in d["notices"]
    ), d["notices"]


def test_user_authored_nodes_stay_editable():
    d = _diagnostics()
    assert "action_selection" in d["editableVars"]
    assert "sample_mechanism" in d["editableVars"]
